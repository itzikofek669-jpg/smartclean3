/**
 * מה התפקיד של המשתמש, לפי מסמך הפרופיל שלו — ומתי עוד אין תשובה.
 *
 * ההבחנה בין `null` ל-`'client'` היא כל העניין. הקוד הקודם קרא את המסמך פעם
 * אחת, ואם הוא לא נמצא הסיק "לקוח". אבל מסך הבית עולה ברגע שנוצר חשבון
 * ההזדהות — לפני שההרשמה הספיקה לכתוב את הפרופיל — ולכן מנקה שזה עתה נרשמה
 * קיבלה את המסך של לקוח, לצמיתות, כי אף אחד לא קרא שוב.
 *
 * מסמך שלא קיים אינו לקוח. הוא תשובה שטרם הגיעה, והקורא חייב להמתין לה.
 *
 * פונקציה טהורה בכוונה: זו ההחלטה שנשברה בייצור, והיא הייתה קבורה בתוך
 * callback של קומפוננטה שאי אפשר להריץ בבדיקה.
 */
export type Role = 'client' | 'cleaner';

export function resolveRole(doc: { exists: boolean; data?: { role?: unknown } | null }): Role | null {
  if (!doc.exists) return null;                 // עוד לא נכתב — לא לנחש
  return doc.data?.role === 'cleaner' ? 'cleaner' : 'client';
}
